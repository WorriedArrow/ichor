//! Generates `docs/linux-abi.md`, the Linux syscall coverage table, from the
//! syscall-number table in `kernel/ichor/src/linuxabi.rs`.
//!
//! Each `pub(super) const NAME: u64 = N;` line inside `mod nr` is one
//! implemented syscall. A trailing `// partial: ...` or `// stub: ...`
//! comment sets its status and note; without one it is "implemented".
//! Everything not listed returns `-ENOSYS`.

use std::fs;

use crate::{Result, workspace_root};

const SOURCE: &str = "kernel/ichor/src/linuxabi.rs";
const DOC: &str = "docs/linux-abi.md";

#[derive(Debug, PartialEq, Eq)]
struct Entry {
    nr: u64,
    name: String,
    status: &'static str,
    note: String,
}

fn parse(src: &str) -> Result<Vec<Entry>> {
    let start = src.find("mod nr {").ok_or("no `mod nr` in linuxabi.rs")?;
    let body = &src[start..];
    let end = body.find("\n}").ok_or("unterminated `mod nr`")?;
    let mut out = Vec::new();
    for line in body[..end].lines() {
        let line = line.trim();
        let Some(rest) = line.strip_prefix("pub(super) const ") else {
            continue;
        };
        let (decl, comment) = match rest.split_once("//") {
            Some((d, c)) => (d.trim(), c.trim()),
            None => (rest.trim(), ""),
        };
        let (name, value) = decl
            .split_once(": u64 =")
            .ok_or_else(|| format!("unparsable syscall line: {line}"))?;
        let nr: u64 = value
            .trim()
            .trim_end_matches(';')
            .trim()
            .parse()
            .map_err(|e| format!("bad syscall number in `{line}`: {e}"))?;
        let (status, note) = if let Some(n) = comment.strip_prefix("partial:") {
            ("partial", n.trim().to_string())
        } else if let Some(n) = comment.strip_prefix("stub:") {
            ("stubbed", n.trim().to_string())
        } else {
            ("implemented", comment.to_string())
        };
        out.push(Entry {
            nr,
            name: name.trim().to_lowercase(),
            status,
            note,
        });
    }
    out.sort_by_key(|e| e.nr);
    Ok(out)
}

fn render(entries: &[Entry]) -> String {
    let count = |s: &str| entries.iter().filter(|e| e.status == s).count();
    let mut md = String::new();
    md.push_str("# Linux ABI coverage (x86-64)\n\n");
    md.push_str(
        "Generated by `cargo xtask linux-abi-table` from the syscall table in\n\
         `kernel/ichor/src/linuxabi.rs`; `cargo xtask lint` fails if this file is\n\
         stale. Do not edit by hand.\n\n",
    );
    md.push_str(&format!(
        "{} implemented, {} partial, {} stubbed. Every other syscall returns\n\
         `-ENOSYS`; which ones to add next is driven by tracing what real images\n\
         (busybox, then Alpine and Debian userlands) call.\n\n",
        count("implemented"),
        count("partial"),
        count("stubbed"),
    ));
    md.push_str("| # | Syscall | Status | Notes |\n|---:|---|---|---|\n");
    for e in entries {
        md.push_str(&format!(
            "| {} | `{}` | {} | {} |\n",
            e.nr, e.name, e.status, e.note
        ));
    }
    md
}

fn generate() -> Result<String> {
    let path = workspace_root().join(SOURCE);
    let src = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    Ok(render(&parse(&src)?))
}

/// Writes `docs/linux-abi.md`.
pub fn write_table() -> Result<()> {
    let md = generate()?;
    let path = workspace_root().join(DOC);
    fs::write(&path, md).map_err(|e| format!("{}: {e}", path.display()))?;
    println!("wrote {}", path.display());
    Ok(())
}

/// Fails if `docs/linux-abi.md` does not match the source table.
pub fn check_table() -> Result<()> {
    let want = generate()?;
    let path = workspace_root().join(DOC);
    let have = fs::read_to_string(&path).unwrap_or_default();
    if have.replace("\r\n", "\n") == want {
        println!("linux-abi.md: up to date");
        Ok(())
    } else {
        Err("docs/linux-abi.md is stale; run `cargo xtask linux-abi-table`".into())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_status_comments() {
        let src = "mod nr {\n    pub(super) const READ: u64 = 0; // partial: files only\n    pub(super) const BRK: u64 = 12; // stub: fails\n    pub(super) const CLOSE: u64 = 3;\n}\n";
        let e = parse(src).unwrap();
        assert_eq!(e.len(), 3);
        assert_eq!(
            (e[0].nr, e[0].name.as_str(), e[0].status),
            (0, "read", "partial")
        );
        assert_eq!((e[1].nr, e[1].status), (3, "implemented"));
        assert_eq!(
            (e[2].nr, e[2].status, e[2].note.as_str()),
            (12, "stubbed", "fails")
        );
        assert!(render(&e).contains("| 12 | `brk` | stubbed | fails |"));
    }

    #[test]
    fn real_table_parses() {
        assert!(generate().unwrap().contains("`read`"));
    }
}
